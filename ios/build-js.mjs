import { build } from 'esbuild'
import { readdirSync, readFileSync } from 'node:fs'
import path from 'node:path'

const root = import.meta.dirname
const outfile = path.join(root, 'VacuumTube/leanback-bundle.js')
const upstreamCss = path.join(root, '../src/preload/util/css.js')

const shimPlugin = {
    name: 'shims',
    setup(b) {
        b.onResolve({ filter: /^(electron|fs|path)$/ }, args => ({ path: path.join(root, 'js/shims', args.path + '.js') }))
        b.onResolve({ filter: /(^|\/)util\/css$/ }, args => {
            if (path.resolve(args.resolveDir, args.path) + '.js' === upstreamCss) {
                return { path: path.join(root, 'js/shims/css.js') }
            }
        })
    }
}

await build({
    absWorkingDir: path.join(root, '..'),
    entryPoints: [path.join(root, 'js/entry.js')],
    bundle: true,
    format: 'iife',
    platform: 'browser',
    target: 'es2022',
    minify: false,
    outfile,
    loader: { '.css': 'text' },
    define: {
        __dirname: '"/src/preload/modules"',
        __VT_LOCALES__: JSON.stringify(readdirSync(path.join(root, '../locale')).filter(f => f.endsWith('.json')).sort())
    },
    plugins: [shimPlugin],
    banner: {
        js: [
            '// GENERATED by ios/build-js.mjs from src/preload (MIT, see LICENSE). Do not edit.',
            '// Includes code adapted from https://github.com/erkserkserks/h264ify',
            '// Copyright (c) 2015 erkserkserks, The MIT License (MIT)'
        ].join('\n')
    },
    logLevel: 'info'
})

const bundle = readFileSync(outfile, 'utf8')
const bad = /require\("(fs|path|electron)"\)|__dirname/.exec(bundle)
if (bad) {
    console.error('bundle check failed: found ' + bad[0])
    process.exit(1)
}
if (bundle.includes('reinjectStylesheets')) {
    console.error('bundle check failed: upstream util/css.js is in the bundle')
    process.exit(1)
}
